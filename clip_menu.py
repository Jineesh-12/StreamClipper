import subprocess
import sys
import time

OUTPUT_ROOT = r"C:\Users\tadvi\StreamClips"
SCRIPT_PATH = os.path.join("scripts", "streamclips.py")

VENV_PYTHON = os.path.expanduser(r"~\.streamclips\venv\Scripts\python.exe")
PYTHON_EXE = VENV_PYTHON if os.path.exists(VENV_PYTHON) else sys.executable

# Automatic defaults (no prompts needed for these)
DEFAULT_TOPIC = "Highlights"
DEFAULT_LAYOUT = "auto"
DEFAULT_FOCUS = ""
DEFAULT_AUTO_FX = True


def clean_input_source(raw: str) -> str:
    cleaned = raw.strip().strip('"').strip("'")
    if cleaned.startswith(("http://", "https://", "file:///")):
        return cleaned
    if os.path.exists(cleaned):
        return "file:///" + os.path.abspath(cleaned).replace("\\", "/")
    return cleaned


def sanitize_folder_name(name: str) -> str:
    cleaned = re.sub(r'[<>:"/\\|?*]+', "", name).strip().rstrip(".")
    cleaned = re.sub(r"\s+", " ", cleaned)
    return cleaned[:80] if cleaned else f"Clips_{time.strftime('%Y-%m-%d_%H-%M-%S')}"


def fetch_video_title(source: str, topic: str) -> str:
    if source.startswith("file:///"):
        local_name = os.path.splitext(os.path.basename(source))[0]
        return sanitize_folder_name(local_name)

    if source.startswith(("http://", "https://")):
        print("   [Fetching video title...]")
        res = subprocess.run(
            [
                PYTHON_EXE,
                "-m",
                "yt_dlp",
                "--cookies-from-browser",
                "firefox",
                "--get-title",
                "--no-playlist",
                source,
            ],
            capture_output=True,
            text=True,
            encoding="utf-8",
            errors="replace",
        )
        if res.returncode == 0 and res.stdout.strip():
            first_line = res.stdout.strip().splitlines()[0].strip()
            return sanitize_folder_name(first_line)

    return sanitize_folder_name(f"{topic}_{time.strftime('%Y-%m-%d_%H-%M-%S')}")


def find_latest_stream_metadata(start_time: float, preferred_folder: str = ""):
    """Reads clips.json / picks.json and transcript.json generated by streamclips.py."""
    clips_data = []
    transcript_segments = []

    search_roots = []
    if preferred_folder and os.path.isdir(preferred_folder):
        search_roots.append(preferred_folder)
    if os.path.isdir(OUTPUT_ROOT) and os.path.abspath(preferred_folder or "") != os.path.abspath(OUTPUT_ROOT):
        search_roots.append(OUTPUT_ROOT)

    for base_dir in search_roots:
        for root, _, files in os.walk(base_dir):
            for fname in files:
                full_p = os.path.join(root, fname)
                if os.path.getmtime(full_p) < start_time - 5:
                    continue
                low = fname.lower()
                if low in ("clips.json", "picks.json"):
                    try:
                        with open(full_p, "r", encoding="utf-8", errors="ignore") as f:
                            loaded = json.load(f)
                            if isinstance(loaded, list):
                                clips_data = loaded
                            elif isinstance(loaded, dict):
                                clips_data = loaded.get("clips", loaded.get("picks", []))
                    except (OSError, ValueError):
                        pass
                elif low == "transcript.json":
                    try:
                        with open(full_p, "r", encoding="utf-8", errors="ignore") as f:
                            loaded = json.load(f)
                            if isinstance(loaded, list):
                                transcript_segments = loaded
                            elif isinstance(loaded, dict):
                                transcript_segments = loaded.get("segments", loaded.get("transcript", []))
                    except (OSError, ValueError):
                        pass
        if clips_data or transcript_segments:
            break
    return clips_data, transcript_segments


def format_ts(sec_val) -> str:
    try:
        s = int(float(sec_val))
        h, rem = divmod(s, 3600)
        m, sec = divmod(rem, 60)
        return f"{h:02d}:{m:02d}:{sec:02d}" if h else f"{m:02d}:{sec:02d}"
    except (TypeError, ValueError):
        return str(sec_val)


def move_new_clips_to_folder(start_time: float, target_folder: str, cache_roots: list[str] | None = None) -> list[str]:
    collected = []
    roots_to_scan = [OUTPUT_ROOT]
    for extra in (cache_roots or []):
        if extra and os.path.isdir(extra) and os.path.abspath(extra) not in {os.path.abspath(r) for r in roots_to_scan}:
            roots_to_scan.append(extra)

    for scan_root in roots_to_scan:
        for root, _, files in os.walk(scan_root):
            in_target = os.path.abspath(root).startswith(os.path.abspath(target_folder))
            for fname in sorted(files):
                if fname.lower().endswith(".mp4"):
                    full_p = os.path.join(root, fname)
                    if os.path.getmtime(full_p) >= start_time - 2:
                        if in_target:
                            collected.append(full_p)
                        else:
                            dest_p = os.path.join(target_folder, fname)
                            shutil.move(full_p, dest_p)
                            collected.append(dest_p)
    return sorted(set(collected))


def create_txt_summaries(
    mp4_files: list[str],
    topic: str,
    video_title: str,
    source_url: str,
    clips_data: list,
    transcript_segments: list,
    target_folder: str = "",
) -> None:
    """Creates per-clip .txt files plus ONE combined ALL_CLIPS_SUMMARY.txt."""
    if not mp4_files:
        return

    by_filename = {
        c.get("file"): c for c in clips_data if isinstance(c, dict) and c.get("file")
    }

    sections = [
        f"SOURCE VIDEO : {video_title}\n"
        f"SOURCE LINK  : {source_url}\n"
        f"TOTAL CLIPS  : {len(mp4_files)}\n"
        f"{'=' * 60}\n"
    ]

    for idx, mp4_path in enumerate(mp4_files, 1):
        stem = os.path.splitext(mp4_path)[0]
        base_name = os.path.basename(stem)
        mp4_name = os.path.basename(mp4_path)
        fallback_title = re.sub(r"^\d+_", "", base_name).replace("-", " ").replace("_", " ").strip().title()

        pick = by_filename.get(mp4_name)
        if not pick and idx - 1 < len(clips_data) and isinstance(clips_data[idx - 1], dict):
            pick = clips_data[idx - 1]
        pick = pick or {}

        clip_title = str(pick.get("title") or fallback_title).strip()[:100]
        why = (
            pick.get("caption")
            or pick.get("reason")
            or pick.get("why")
            or pick.get("description")
            or f"Peak {topic} moment from '{video_title}'."
        )
        score = pick.get("score", "N/A")
        start_sec = pick.get("start")
        end_sec = pick.get("end")
        if end_sec is None and start_sec is not None and pick.get("seconds") is not None:
            end_sec = float(start_sec) + float(pick["seconds"])

        time_str = (
            f"{format_ts(start_sec)} -> {format_ts(end_sec)}"
            if start_sec is not None and end_sec is not None
            else "Auto-detected"
        )

        spoken_lines = []
        if start_sec is not None and end_sec is not None and transcript_segments:
            for seg in transcript_segments:
                if isinstance(seg, dict):
                    s_t = float(seg.get("start", 0))
                    e_t = float(seg.get("end", 0))
                    if e_t >= float(start_sec) and s_t <= float(end_sec):
                        txt = str(seg.get("text", "")).strip()
                        if txt:
                            spoken_lines.append(txt)

        captions_text = (
            " ".join(spoken_lines)
            if spoken_lines
            else str(pick.get("why") or f"{clip_title} (Captions burned directly into the clip).")
        )

        raw_tags = pick.get("hashtags")
        if isinstance(raw_tags, list) and raw_tags:
            hashtags = " ".join(str(t) for t in raw_tags)
        else:
            clean_tag = re.sub(r"[^a-zA-Z0-9]", "", topic) or "Gaming"
            hashtags = f"#{clean_tag} #Shorts #Viral #Clips #Highlights"

        desc_body = f"{why}\n\n{hashtags}".strip()

        per_clip_txt = f"{stem}.txt"
        with open(per_clip_txt, "w", encoding="utf-8") as cf:
            cf.write(f"TITLE: {clip_title}\nDESCRIPTION:\n{desc_body}\n")

        sections.append(
            f"\nCLIP #{idx:02d}     : {mp4_name}\n"
            f"TITLE        : {clip_title}\n"
            f"VIRAL SCORE  : {score}/100\n"
            f"TIMESTAMPS   : {time_str}\n"
            f"{'-' * 60}\n"
            f"DESCRIPTION  :\n"
            f"{desc_body}\n"
            f"{'-' * 60}\n"
            f"SPOKEN CAPTIONS / WHAT HAPPENS IN THIS CLIP :\n"
            f"{captions_text}\n"
            f"{'=' * 60}\n"
        )

    batch_folder = target_folder or os.path.dirname(mp4_files[0])
    os.makedirs(batch_folder, exist_ok=True)
    combined_txt = os.path.join(batch_folder, "ALL_CLIPS_SUMMARY.txt")
    with open(combined_txt, "w", encoding="utf-8") as tf:
        tf.write("".join(sections))


def main() -> None:
    print("\n" + "=" * 60)
    print("   STREAM CLIPPER STUDIO — LOCAL CLIPPER")
    print("=" * 60)

    while True:
        print()
        raw_source = input("1. Paste a YouTube/Twitch link OR drag a video file (or 'exit'): ").strip()
        if raw_source.lower() in ("exit", "quit", "q"):
            break
        if not raw_source:
            continue

        source = clean_input_source(raw_source)
        topic = DEFAULT_TOPIC
        num_clips = input("2. How many clips do you want? [default: 6]: ").strip() or "6"
        min_sec = input("3. Shortest clip length in seconds [default: 20]: ").strip() or "20"
        max_sec = input("4. Longest clip length in seconds [default: 60]: ").strip() or "60"
        layout = DEFAULT_LAYOUT
        focus = DEFAULT_FOCUS
        bleep_ans = input("5. Mute (beep) bad words? (Y/N) [default: Y]: ").strip().lower()
        bleep_on = bleep_ans not in ("n", "no")
        auto_fx_on = DEFAULT_AUTO_FX

        video_title = fetch_video_title(source, topic)
        os.makedirs(OUTPUT_ROOT, exist_ok=True)
        batch_folder = os.path.join(OUTPUT_ROOT, video_title)
        if os.path.exists(batch_folder):
            batch_folder = os.path.join(OUTPUT_ROOT, f"{video_title}_{time.strftime('%H-%M-%S')}")
        os.makedirs(batch_folder, exist_ok=True)

        out_drive = os.path.splitdrive(os.path.abspath(batch_folder))[0] or "C:"
        download_home = os.path.join(out_drive + os.sep, "StreamClipsDownloads")
        os.makedirs(download_home, exist_ok=True)

        cmd = [
            PYTHON_EXE,
            "-u",
            SCRIPT_PATH,
            "clip",
            source,
            "--brain",
            "gemini-api",
            "--topic",
            topic,
            "--clips",
            str(num_clips),
            "--layout",
            layout,
            "--min",
            str(min_sec),
            "--max",
            str(max_sec),
            "--language",
            "en",
            "--fast",
            "--repick",
        ]

        if source.startswith(("http://", "https://")):
            cmd += ["--cookies", "firefox"]
        if focus:
            cmd += ["--focus", focus]

        print(f"\n[Folder Ready] {batch_folder}")
        print(f"[Download/Cache Drive] {download_home}")
        print(
            f"[Processing] Picking {num_clips} clip(s) ({min_sec}s-{max_sec}s) "
            f"[topic={topic}, layout={layout}, auto-fx=ON]...\n"
        )
        run_start = time.time()
        run_env = os.environ.copy()
        run_env["STREAMCLIPS_BLEEP"] = "1" if bleep_on else "0"
        run_env["STREAMCLIPS_AUTO_FX"] = "1" if auto_fx_on else "0"
        run_env["STREAMCLIPS_OUT_DIR"] = batch_folder
        run_env["STREAMCLIPS_HOME"] = download_home
        subprocess.run(cmd, env=run_env)

        clips_data, transcript_segments = find_latest_stream_metadata(run_start, batch_folder)
        moved_clips = move_new_clips_to_folder(run_start, batch_folder, [download_home])

        if moved_clips:
            create_txt_summaries(
                moved_clips,
                topic,
                video_title,
                raw_source,
                clips_data,
                transcript_segments,
                batch_folder,
            )
            print(
                f"\nDone! Saved {len(moved_clips)} clip(s) "
                f"+ detailed .txt files inside:\n   {batch_folder}"
            )
            subprocess.run(["explorer", batch_folder])
        else:
            print("\nNo new clips were generated—check the message above.")


if __name__ == "__main__":
    main()

